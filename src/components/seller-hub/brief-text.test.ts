import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { briefText } from "./hub-task-present";

describe("briefText: короткий конспект для карточки задачи", () => {
  const text =
    "Основа для кашпо 12 литров 5 штук: на 1 продажу до себестоимости уже 120 ₽, цена продавца 590 ₽. Период: 28 окт. Оценка потерь: 12 шт. (оценка).";

  it("убирает название товара в начале и служебные фразы", () => {
    const out = briefText(text, ["Основа для кашпо 12 литров 5 штук"], 1, 170);
    assert.equal(out, "На 1 продажу до себестоимости уже 120 ₽, цена продавца 590 ₽.");
  });

  it("не оставляет название товара внутри текста", () => {
    const out = briefText("Цена товара Крем для рук ниже закупки.", ["Крем для рук"], 1, 170);
    assert.ok(!out.includes("Крем для рук"));
  });

  it("обрезает длинный текст по границе слова с многоточием", () => {
    const out = briefText("Очень длинное предложение про остаток товара на складе и скорость продаж за последние недели.", [], 1, 40);
    assert.ok(out.endsWith("…"));
    assert.ok(out.length <= 41);
  });

  it("пустой текст даёт пустую строку", () => {
    assert.equal(briefText("", []), "");
  });
});
