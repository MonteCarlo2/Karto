/**
 * Собирает docs/seller-hub/agent-rules-registry.md из кода: числа берутся из параметров сценариев и проверок, поэтому документ не расходится с кодом.
 * Пометки у чисел как в стандарте (docs/seller-hub/rules-standard.md): М — математика, П — политика продукта, К — стартовое значение для калибровки, Р — нужно решение владельца.
 *
 *   npx tsx scripts/gen-agent-rules-doc.ts
 */
import { writeFileSync } from "node:fs";
import { ACTION_SPECS } from "@/lib/seller-hub/agent/actions";
import { DEFAULT_PRICE_GUARD } from "@/lib/seller-hub/agent/guardrails";
import { PLAYBOOKS, type PlaybookId } from "@/lib/seller-hub/agent/playbooks";
import { MAX_BATCH_SHARE, MIN_BATCH } from "@/lib/seller-hub/agent/scenario-run";
import { BASELINE_DAYS, MATERIAL_FLOOR, MATERIAL_SHARE, MAX_DAYS_AFTER, MIN_BASELINE_DAYS, MIN_DAYS_AFTER, MIN_EXPECTED_ORDERS, Z_THRESHOLD } from "@/lib/seller-hub/agent/outcomes";
import { NEGATIVE_MAX_AGE_DAYS } from "@/lib/seller-hub/agent/signals";
import { agentModeLabel, TASK_AGENT_MAP } from "@/lib/seller-hub/agent/task-map";

const pct = (v: number) => `${Math.round(v * 1000) / 10}%`;
const lines: string[] = [];
const out = (text = "") => lines.push(text);

out("# Реестр правил агента Seller Hub");
out();
out("Документ собирается из кода командой `npx tsx scripts/gen-agent-rules-doc.ts`: числа берутся из параметров, поэтому он не расходится с кодом. Чтобы изменить правило, правится параметр в коде (`src/lib/seller-hub/agent/`), документ пересобирается.");
out();
out("Пометки у чисел те же, что в стандарте правил (`rules-standard.md`): **М** — математика или определение; **П** — политика продукта, выбрана нами; **К** — стартовое значение, нужна калибровка по данным; **Р** — нужно решение владельца.");
out("Колонка «Источник»: **JVO** — число взято из публичного описания стратегий JVO (docs/seller-hub/agents-jvo-deep.md); **KARTO** — наш стандарт или статистика; **уточнено** — у JVO формулировка неясна или плоха для малого магазина, мы выбрали осторожное толкование.");
out();
out("Сверка чисел с опытом продавцов и документацией WB: `agent-experience-base.md` (там источники и уровень доверия каждого факта).");
out();
out("## Честно о проверенности");
out();
out("- Числа из JVO заявлены самим JVO как проверенные на практике их студии. Мы не проверяли их независимо.");
out("- Математика (пол цены, статистика тренда) проверяется тестами. Остальное (**К**) на нашем магазине пока не откалибровано: для этого агент записывает «было → стало» и измеряет результат (журнал решений, шаг 3 плана).");
out("- До калибровки агент только предлагает, человек подтверждает; цена никогда не меняется автоматически.");
out();

out("## 1. Ограничители цены (программа, обойти нельзя)");
out();
out("| Правило | Значение | Пометка | Зачем |");
out("|---|---|---|---|");
out(`| Пол цены | безубыточная цена со скидкой продавца + ${pct(DEFAULT_PRICE_GUARD.breakEvenCushion)} запаса | П, К | Цена не должна уходить в убыток; человек может только поднять пол, не опустить |`);
out(`| Максимальный шаг за раз | ${pct(DEFAULT_PRICE_GUARD.maxStep)} | П, К | Резкие скачки пугают покупателей и ломают измерение результата |`);
out(`| Пауза после изменения | ${DEFAULT_PRICE_GUARD.cooldownHours} ч | П | Нужно время, чтобы увидеть результат прошлого шага |`);
out(`| Предел общего снижения | не больше ${PLAYBOOKS.grow_no_price_war.params.maxTotalCut}% от прежней цены внутри сценария | П, К | WB отправляет в карантин цены снижение более чем на 33,3% (источник в agent-experience-base.md) |`);
out(`| Размер пачки | цену меняем не больше чем у ${Math.round(MAX_BATCH_SHARE * 100)}% товаров за раз (не меньше ${MIN_BATCH}), самые важные первыми | К | Практика селлеров: менять цену на части ассортимента и смотреть реакцию; так результат можно измерить |`);
out("| Нулевой остаток | снижать цену нельзя | М | Нечего продавать, снижение только теряет деньги |");
out("| Нет безубыточной цены | снижать нельзя, повышать можно | М | Нельзя доказать, что цена не уйдёт в убыток (нет себестоимости или доставок за 90 дней) |");
out("| Сверка перед записью | цена и скидка в WB должны совпадать с теми, что видел человек | М | Не затирать чужую правку |");
out();

out("## 2. Показатели, на которых строятся сценарии");
out();
out("| Показатель | Как считается | Пометка | Источник |");
out("|---|---|---|---|");
out("| Дни запаса и дни до нулевого остатка | из досье задач: спрос по дням наличия, сглаженный выкуп, доступный остаток (стандарт §3.2); одна формула с разделом «Задачи» | М | KARTO |");
out("| Запас без движения | остаток есть, заказов нет ни в текущем, ни в прошлом окне воронки: 365 дней | П | JVO |");
out(`| Тренд падения/роста заказов | сколько дней подряд заказы статистически ниже/выше обычного (ожидание по медиане 28 дней с поправкой на день недели, разброс по MAD); серия считается, если отклонение ≥ 15% суммы ожидаемого; мало истории: тренд неизвестен | М, К | KARTO (как в событиях) |`);
out(`| Негатив в окне отзывов | оценка 1–3★ среди последних 10 отзывов, видимых на карточке, не старше ${NEGATIVE_MAX_AGE_DAYS} дней | П | JVO, уточнено |`);
out("| Конверсия в корзину | за окно воронки; верится только при ≥ 300 просмотров | К | JVO, уточнено |");
out();

const stepsText = (steps: Array<[number, number]>) => steps.map(([d, s]) => `≥${d} дн.: −${s}%/день`).join("; ");
const ruleRows = (id: PlaybookId): string[] => {
  const p = PLAYBOOKS[id].params;
  const rows: string[] = [];
  rows.push(`| Защита наличия | дни до нуля ${p.protect.map(([d, s]) => `≤${d}: +${s}%`).join("; ")} | П (JVO) | перекрывает всё остальное |`);
  if (p.negativeCut > 0) rows.push(`| Негатив | оценка 1–3★ в окне отзывов: цена временно на ${p.negativeCut}% ниже прежней, пока окно не очистится | П (JVO), уточнено | уровень от опорной цены, а не накопление |`);
  if (p.trendSteps.length > 0) rows.push(`| Падение заказов | ${stepsText(p.trendSteps)}; стоп в первый день без падения | К (JVO) | только при статистически подтверждённом тренде |`);
  if (p.overstock) rows.push(`| Завал | запас >${p.overstock.start} дн. или (до нуля >${p.overstock.startOos} дн. и конверсия <${p.overstock.startCart}%): −${p.overstock.firstStep}% разово, затем −${p.turnoverStep}% раз в ${p.turnoverEveryDays} дня, пока запас не станет ≤${p.targetTurnover} дн. | К (JVO) | распродажа продолжается между 60 и 90 днями (гистерезис) |`);
  else if (Number.isFinite(p.highTurnover)) rows.push(`| Высокая оборачиваемость | запас >${p.highTurnover} дн.: −${p.turnoverStep}% раз в ${p.turnoverEveryDays} дня до ≤${p.targetTurnover} дн. | К (JVO) | |`);
  if (p.cartLowBelow > 0) rows.push(`| Слабая конверсия | <${p.cartLowBelow}% при ≥${p.minCartSample} просмотров: −${p.cartLowStep}%, не чаще раза в ${p.cartLowEveryDays} дней | К, уточнено | у JVO без периодичности |`);
  rows.push(`| Суточный предел снижения | не больше ${p.dailyCap}% за день суммарно | П, К | |`);
  const r = p.recover;
  rows.push(`| Возврат к прежней цене | +${r.step}%/день (+${r.step + 1}% при росте заказов ≥5 дн.), когда нет падения и негатива${r.cleanDays > 0 ? `, ${r.cleanDays} дня без негатива` : ""}${r.minCart != null ? `, конверсия ≥${r.minCart}%` : ""}, запас ≤${r.maxTurnover} дн.${r.minOos > 0 ? `, до нуля >${r.minOos} дн.` : ""} | К (JVO) | |`);
  if (p.raise) {
    const q = p.raise;
    if (q.step > 0) rows.push(`| Повышение | конверсия >${q.minCart}%, падения нет, запас ≤${q.maxTurnover} дн., до нуля >${q.minOos} дн.: +${q.step}%, не чаще раза в ${q.everyDays} дня | К (JVO) | при свежем негативе повышений нет |`);
    rows.push(`| Поддержка роста | заказы растут ≥${q.supportRiseDays} дн., конверсия ≥${q.supportMinCart}%, запас в норме: +${q.supportStep}% раз в ${q.everyDays} дня | К (JVO) | |`);
  }
  return rows;
};

out("## 3. Стратегии цен");
out();
for (const id of Object.keys(PLAYBOOKS) as PlaybookId[]) {
  out(`### ${PLAYBOOKS[id].title}`);
  out();
  out(PLAYBOOKS[id].goal);
  out();
  out("| Правило | Условие и шаг | Пометка | Примечание |");
  out("|---|---|---|---|");
  for (const row of ruleRows(id)) out(row);
  out();
}

out("## 4. Действия агента");
out();
out("| Действие | Риск | Вернуть можно | Сверка перед записью | Может ли когда-нибудь выполняться без подтверждения | Как проверить после |");
out("|---|---|---|---|---|---|");
const rev = { full: "полностью", partial: "частично", none: "нет" } as const;
const risk = { low: "низкий", medium: "средний", high: "высокий" } as const;
for (const [type, spec] of Object.entries(ACTION_SPECS)) {
  out(`| ${spec.label} (\`${type}\`) | ${risk[spec.risk]} | ${rev[spec.reversibility]} | ${spec.needsFreshnessCheck ? "да" : "нет"} | ${spec.autoEligible ? "да, только по отдельному правилу владельца" : "нет"} | ${spec.verify} |`);
}
out();

out("## 5. Что агент делает по каждой задаче");
out();
out("| Задача | Роль агента | Действия | Сценарий | Пояснение |");
out("|---|---|---|---|---|");
for (const [type, rule] of Object.entries(TASK_AGENT_MAP)) {
  out(`| \`${type}\` | ${agentModeLabel[rule.mode]} | ${rule.actions.join(", ") || "—"} | ${rule.playbook ?? "—"} | ${rule.note} |`);
}
out();

out("## 6. ИИ-проверка предложений по ценам");
out();
out("Включается переменной `SELLER_HUB_AGENT_AI=1` (платная, по умолчанию выключена). Работает только над предложениями, которые уже прошли правила и ограничители цены.");
out();
out("| Участник | Что делает | Чего не может |");
out("|---|---|---|");
out("| Аналитик (ИИ №1) | ставит диагноз из закрытого списка (мало просмотров, цена, карточка, негатив, запас, спрос, реклама, здоровый товар, мало данных), говорит, поддерживает ли действие алгоритма, подкрепляет выводы цифрами из фактов | называть цену, шаг, сумму; добавлять действия |");
out("| Проверяющий (ИИ №2) | не видит ответа аналитика, ищет причины, почему действие делать нельзя или рано (мало данных, другая причина, ухудшит экономику, случайный всплеск) | предлагать свои действия, называть числа цены |");
out("| Программа | проверяет, что каждая цифра в ответах ИИ совпадает с фактами (расхождение больше 2%: ответ не учитывается); решает итог | — |");
out();
out("Итог двух мнений (детерминированный): **согласовано** — оба поддерживают; **спорно** — показываем с предупреждением, решает человек; **скрыто** — аналитик против, а проверяющий не одобряет (причина в логе и заметках); **ИИ-проверка не выполнена** — нейросеть недоступна или ответ не подтвердился фактами, решение остаётся за правилами и ограничителями цены. ИИ может только добавить осторожности, но не может разрешить то, что запретили ограничители.");
out();
out("Стоимость: кэш по отпечатку фактов (те же цифры повторно не оплачиваются), пачки по 6 товаров, суточный предел вызовов. Живой замер на 4 товарах: около 0,006 $ за два вызова.");
out();
out("## 7. Измерение результата действия");
out();
out("После выполнения цены агент через неделю сравнивает заказы товара до и после (метод стандарта §2: тест Пуассона плюс существенность). Это сравнение «до/после», а не доказательство причины.");
out();
out("| Параметр | Значение | Пометка |");
out("|---|---|---|");
out(`| Окно «до» | ${BASELINE_DAYS} законченных дней перед днём изменения (нужно не меньше ${MIN_BASELINE_DAYS}) | М, П |`);
out(`| Окно «после» | от ${MIN_DAYS_AFTER} до ${MAX_DAYS_AFTER} законченных дней; день изменения и сегодняшний в сравнение не входят | П |`);
out(`| Достоверность | |z| ≥ ${Z_THRESHOLD} (около 95%) | М |`);
out(`| Существенность | изменение не меньше ${Math.round(MATERIAL_SHARE * 100)}% ожидаемого и не меньше ${MATERIAL_FLOOR} заказов за период | П, К |`);
out(`| Мало заказов | ожидалось меньше ${MIN_EXPECTED_ORDERS} заказов за период: вердикт «судить нельзя», а не «эффекта нет» | П |`);
out("| Вердикты | улучшение, ухудшение, заметного изменения нет, слишком рано, судить нельзя | |");
out();

writeFileSync("docs/seller-hub/agent-rules-registry.md", `${lines.join("\n")}\n`, "utf8");
console.log(`Записано: docs/seller-hub/agent-rules-registry.md (${lines.length} строк)`);
